const TRANSLATABLE_ATTRIBUTES = ["aria-label", "placeholder", "title", "alt"];

function translateNode(node) {
  if (typeof node === "string") {
    const trimmed = node.trim();
    const translation = FILIPINO_TRANSLATIONS[trimmed];
    if (!translation) return node;
    return node.replace(trimmed, translation);
  }
  if (Array.isArray(node)) return node.map(translateNode);
  if (!isValidElement(node)) return node;

  const props = { ...node.props };
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    if (typeof props[attribute] === "string") {
      props[attribute] = FILIPINO_TRANSLATIONS[props[attribute]] || props[attribute];
    }
  }
  props.children = Children.map(node.props.children, translateNode);
  return cloneElement(node, props);
}

export function translateStudentUI(node, language) {
  return language === "fil" ? translateNode(node) : node;
}
